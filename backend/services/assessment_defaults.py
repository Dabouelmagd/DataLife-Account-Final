def default_questions(company_id: str, user_id: str = None):
    """AssessmentQuestion documents for one company."""
    from models.assessment import AssessmentQuestion
    docs = []
    for axis, text, opts in PSYCHOMETRIC:
        docs.append(AssessmentQuestion(
            company_id=company_id, kind="psychometric", text=text, dichotomy=axis,
            options=[{"key": k, "text": t, "pole": p} for k, t, p in opts],
            created_by=user_id).model_dump(mode="json") | {"source": "default"})
    for area, text, opts, correct in APTITUDE:
        docs.append(AssessmentQuestion(
            company_id=company_id, kind="aptitude", text=text, area=area, correct_option=correct,
            options=[{"key": k, "text": t} for k, t in opts],
            created_by=user_id).model_dump(mode="json") | {"source": "default"})
    return docs
